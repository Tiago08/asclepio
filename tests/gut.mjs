const habitual={...BASICS.find(f=>f.name==='Arroz blanco cocido'),id:'habit'};
const logs=Array.from({length:60},(_,i)=>({id:String(i),food_id:'habit',quantity:1.5,momento:'Almuerzo',log_date:day(i),log_time:'12:00'}));
const catalog=[habitual,...BASICS.filter(f=>f.usda_fdc_id!==habitual.usda_fdc_id)];
const args={catalog,targets:[],totals:{},coverage:{},goals:{goal_kcal:2000,goal_protein_g:150},kcal:500,protein:150,logs,meal:'Almuerzo'};
const before=JSON.stringify({logs,catalog});const suggestions=recommendFoods(args);
assert.ok(suggestions.items.some(item=>item.variant===habitual.name));
assert.equal(JSON.stringify({logs,catalog}),before,'Mostrar o ignorar sugerencias es neutro y no registra preferencias');
const rejected=suggestions.items[0].key;
